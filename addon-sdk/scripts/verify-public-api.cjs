const fs = require("node:fs");
const path = require("node:path");

const REQUIRED_EXPORTS = [
  { label: "root", key: "." },
  { label: "clockify", key: "./clockify" },
  { label: "adapters", key: "./adapters" },
  { label: "fetch-adapter", key: "./adapters/fetch", optional: true },
  { label: "node-adapter", key: "./adapters/node", optional: true },
  { label: "express-adapter", key: "./adapters/express", optional: true },
  { label: "client", key: "./client", optional: true },
  { label: "ui", key: "./ui", optional: true },
  { label: "testing", key: "./testing" },
];

function argValue(name) {
  const index = process.argv.indexOf(name);
  if (index === -1) return undefined;
  return process.argv[index + 1];
}

function normalizePath(value) {
  return value.split(path.sep).join("/");
}

function normalizeText(value) {
  return value.replace(/\r\n/g, "\n").trimEnd();
}

function fail(message) {
  console.error(message);
  process.exit(1);
}

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (error) {
    fail(`Failed to read ${file}: ${error.message}`);
  }
}

function exportTypesSpecifier(packageJson, exportKey) {
  const entry = packageJson.exports && packageJson.exports[exportKey];
  if (entry && typeof entry === "object") {
    if (
      entry.import &&
      typeof entry.import === "object" &&
      typeof entry.import.types === "string"
    ) {
      return entry.import.types;
    }

    if (typeof entry.types === "string") {
      return entry.types;
    }
  }

  fail(`Missing package.json exports["${exportKey}"] import types declaration.`);
}

function entrypointsFromPackageJson(packageJson, packageRoot) {
  return REQUIRED_EXPORTS.filter(
    (entry) => !entry.optional || packageJson.exports?.[entry.key] !== undefined,
  ).map((entry) => ({
    label: entry.label,
    file: path.resolve(packageRoot, exportTypesSpecifier(packageJson, entry.key)),
  }));
}

function resolveDeclaration(fromFile, specifier) {
  if (!specifier.startsWith(".")) return undefined;

  const base = path.resolve(path.dirname(fromFile), specifier);
  const candidates = specifier.endsWith(".js")
    ? [base.replace(/\.js$/, ".d.ts")]
    : [`${base}.d.ts`, path.join(base, "index.d.ts")];
  return candidates.find((candidate) => fs.existsSync(candidate));
}

function collectExportedDeclarations(file, distDir, seen = new Set()) {
  const absoluteFile = path.resolve(file);
  if (seen.has(absoluteFile)) return [];
  seen.add(absoluteFile);

  if (!fs.existsSync(absoluteFile)) {
    fail(`Missing public API declaration file: ${absoluteFile}`);
  }

  const content = normalizeText(fs.readFileSync(absoluteFile, "utf8"));
  const relativePath = normalizePath(path.relative(distDir, absoluteFile));
  const records = [{ path: relativePath, content }];
  const exportPattern =
    /export\s+(?:\*\s*(?:as\s+\w+\s*)?from|(?:type\s+)?\{[\s\S]*?\}\s*from)\s*["']([^"']+)["']/g;

  for (const match of content.matchAll(exportPattern)) {
    const resolved = resolveDeclaration(absoluteFile, match[1]);
    if (resolved) {
      records.push(...collectExportedDeclarations(resolved, distDir, seen));
    }
  }

  return records;
}

function renderSnapshot(entrypoints, distDir) {
  const sections = [
    "# Public API Snapshot",
    "",
    "Generated by `npm run verify:public-api -- --update` after `npm run build`.",
    "This file tracks the declaration surfaces exported by the package entry points.",
    "",
  ];

  for (const entry of entrypoints) {
    sections.push(`## ${entry.label}`, "");

    for (const record of collectExportedDeclarations(entry.file, distDir)) {
      sections.push(`### ${record.path}`, "", "```ts", record.content, "```", "");
    }
  }

  return `${sections.join("\n").trimEnd()}\n`;
}

function firstDifference(expected, actual) {
  const expectedLines = expected.split("\n");
  const actualLines = actual.split("\n");
  const length = Math.max(expectedLines.length, actualLines.length);

  for (let i = 0; i < length; i += 1) {
    if (expectedLines[i] !== actualLines[i]) {
      return {
        line: i + 1,
        expected: expectedLines[i] ?? "<missing>",
        actual: actualLines[i] ?? "<missing>",
      };
    }
  }

  return undefined;
}

const defaultPackageRoot = path.resolve(__dirname, "..");
const packageJsonPath = path.resolve(
  argValue("--package-json") ?? path.join(defaultPackageRoot, "package.json"),
);
const packageRoot = path.dirname(packageJsonPath);
const distDir = path.resolve(argValue("--dist-dir") ?? path.join(packageRoot, "dist", "esm"));
const snapshotPath = path.resolve(
  argValue("--snapshot") ?? path.join(packageRoot, "public-api.snapshot.md"),
);
const update = process.argv.includes("--update");
const packageJson = readJson(packageJsonPath);
const actual = renderSnapshot(entrypointsFromPackageJson(packageJson, packageRoot), distDir);

if (update) {
  fs.writeFileSync(snapshotPath, actual, "utf8");
  console.log(`Public API snapshot updated: ${snapshotPath}`);
  process.exit(0);
}

if (!fs.existsSync(snapshotPath)) {
  fail(`Missing public API snapshot: ${snapshotPath}. Run npm run verify:public-api -- --update.`);
}

const expected = normalizeText(fs.readFileSync(snapshotPath, "utf8")) + "\n";
if (actual !== expected) {
  const diff = firstDifference(expected, actual);
  const suffix = diff
    ? ` First difference at line ${diff.line}.\nExpected: ${diff.expected}\nActual:   ${diff.actual}`
    : "";
  fail(
    `Public API snapshot is out of date. Run npm run build && npm run verify:public-api -- --update.${suffix}`,
  );
}

console.log("Public API snapshot OK.");
